// Generate profiles.mbt from an installed franc-min 6.2.0.
//
// Usage:
//   npm install --prefix <tmp> --no-save --ignore-scripts franc-min@6.2.0
//   node tools/gen_profiles.mjs <tmp>/node_modules/franc-min [profiles.mbt]
//   moon fmt

import {readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {pathToFileURL} from 'node:url'

const [dir, output = 'profiles.mbt'] = process.argv.slice(2)
if (!dir) {
  throw new Error('usage: node tools/gen_profiles.mjs <franc-min dir> [output]')
}

const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'))
if (pkg.name !== 'franc-min' || pkg.version !== '6.2.0') {
  throw new Error(`expected franc-min 6.2.0, found ${pkg.name} ${pkg.version}`)
}

const load = (file) => import(pathToFileURL(path.join(dir, file)).href)
const {data} = await load('data.js')
const {expressions} = await load('expressions.js')

const constructor = (code) => code[0].toUpperCase() + code.slice(1)
const literal = (value) => {
  if (/["\\\u0000-\u001F\u007F]/.test(value)) {
    throw new Error(`unexpected character in ${JSON.stringify(value)}`)
  }
  return `"${value}"`
}

const lines = [
  '// Generated by tools/gen_profiles.mjs from franc-min 6.2.0. Do not edit.',
  '',
  '///|',
  '/// Keys of franc-min expressions.js in order. A three-letter key is the',
  '/// only language written in that script.',
  'let franc_script_keys : FixedArray[String] = [',
  ...Object.keys(expressions).map((key) => `  ${literal(key)},`),
  ']'
]

for (const script of Object.keys(data)) {
  lines.push(
    '',
    '///|',
    `/// ${script} trigram profiles: 300 trigrams joined by \`|\`, most`,
    '/// frequent first.',
    `let ${script.toLowerCase()}_profiles : FixedArray[(Lang, String)] = [`
  )
  for (const [code, model] of Object.entries(data[script])) {
    lines.push(`  (${constructor(code)}, ${literal(model)}),`)
  }
  lines.push(']')
}

lines.push(
  '',
  '///|',
  '/// Scripts whose languages are told apart by trigram profiles.',
  'let trigram_profiles : FixedArray[(Script, FixedArray[(Lang, String)])] = [',
  ...Object.keys(data).map(
    (script) => `  (${script}, ${script.toLowerCase()}_profiles),`
  ),
  ']'
)

writeFileSync(output, lines.join('\n') + '\n')
