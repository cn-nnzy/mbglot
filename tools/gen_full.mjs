// Generate the data and golden test of the `full` package from an installed
// franc 6.2.0 (186 languages; franc-min is the 82-language subset).
//
// Usage:
//   npm install --prefix <tmp> --no-save --ignore-scripts franc@6.2.0
//   curl -fsSL -o <tmp>/fixtures.js \
//     https://raw.githubusercontent.com/wooorm/franc/3f9f0b51a96c5df32a407dad865a3011ac0fa2d1/test/fixtures.js
//   node tools/gen_full.mjs <tmp>/node_modules/franc <tmp>/fixtures.js [full]
//   moon fmt
//
// Writes <full>/data.mbt (script ranges and trigram profiles) and
// <full>/golden_test.mbt (francAll results for franc's fixtures in the
// supported languages and for tools/golden_samples.json; the ten best
// entries of each and the number of entries).

import {createHash} from 'node:crypto'
import {readFileSync, writeFileSync} from 'node:fs'
import path from 'node:path'
import {fileURLToPath, pathToFileURL} from 'node:url'

const FIXTURES_SHA256 =
  '6823ea979fc5d8e019d6c8d26204ddedf6096429814acdccd4e1e9e56b84def6'

const [dir, fixturesPath, output = 'full'] = process.argv.slice(2)
if (!dir || !fixturesPath) {
  throw new Error(
    'usage: node tools/gen_full.mjs <franc dir> <fixtures.js> [output dir]'
  )
}

const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'))
if (pkg.name !== 'franc' || pkg.version !== '6.2.0') {
  throw new Error(`expected franc 6.2.0, found ${pkg.name} ${pkg.version}`)
}
const digest = createHash('sha256')
  .update(readFileSync(fixturesPath))
  .digest('hex')
if (digest !== FIXTURES_SHA256) {
  throw new Error(`unexpected fixtures.js (sha256 ${digest})`)
}

const load = (file) => import(pathToFileURL(file).href)
const {francAll} = await load(path.join(dir, 'index.js'))
const {data} = await load(path.join(dir, 'data.js'))
const {expressions} = await load(path.join(dir, 'expressions.js'))
const {fixtures} = await load(path.resolve(fixturesPath))

const string = (value) => {
  let out = '"'
  for (const char of value) {
    const code = char.codePointAt(0)
    if (char === '"' || char === '\\') out += '\\' + char
    else if (code < 0x20 || code === 0x7f) out += `\\u{${code.toString(16)}}`
    else out += char
  }
  return out + '"'
}
const hex = (n) => '0x' + n.toString(16).toUpperCase()

// The code points each expression matches as one match, as inclusive
// ranges. franc counts matches, and a surrogate pair in an expression
// matches one astral code point.
const ranges = (expression) => {
  const re = new RegExp(expression.source, expression.flags)
  const out = []
  let start = -1
  for (let cp = 0; cp <= 0x110000; cp++) {
    let member = false
    if (cp < 0x110000 && (cp < 0xd800 || cp > 0xdfff)) {
      const text = String.fromCodePoint(cp)
      const found = text.match(re)
      member = found !== null && found.length === 1 && found[0] === text
    }
    if (member && start < 0) start = cp
    if (!member && start >= 0) {
      out.push(start, cp - 1)
      start = -1
    }
  }
  return out
}

const lines = [
  '// Generated by tools/gen_full.mjs from franc 6.2.0. Do not edit.',
  '',
  '///|',
  '/// The keys of franc expressions.js in order, each with the code point',
  '/// ranges (inclusive pairs) its expression matches. A three-letter key',
  '/// is the only language written in that script.',
  'let scripts : FixedArray[(String, FixedArray[Int32])] = ['
]
for (const [key, expression] of Object.entries(expressions)) {
  const pairs = ranges(expression)
  lines.push(`  (${string(key)}, [${pairs.map(hex).join(', ')}]),`)
}
lines.push(
  ']',
  '',
  '///|',
  '/// The trigram profiles of each script whose languages franc tells',
  '/// apart by trigrams: ISO 639-3 code and 300 trigrams joined by `|`, most',
  '/// frequent first.',
  'let profiles : FixedArray[(String, FixedArray[(String, String)])] = ['
)
for (const [script, languages] of Object.entries(data)) {
  lines.push(`  (${string(script)}, [`)
  for (const [code, model] of Object.entries(languages)) {
    lines.push(`    (${string(code)}, ${string(model)}),`)
  }
  lines.push('  ]),')
}
lines.push(']')
writeFileSync(path.join(output, 'data.mbt'), lines.join('\n') + '\n')

const supported = new Set(Object.keys(expressions))
for (const languages of Object.values(data)) {
  for (const code of Object.keys(languages)) supported.add(code)
}
const here = path.dirname(fileURLToPath(import.meta.url))
const samples = JSON.parse(
  readFileSync(path.join(here, 'golden_samples.json'), 'utf8')
)
const cases = []
for (const [name, {iso6393, fixture}] of Object.entries(fixtures)) {
  if (supported.has(iso6393)) cases.push({name: `fixture ${name}`, text: fixture})
}
for (const sample of samples) {
  cases.push({
    name: sample.name,
    text: sample.text.repeat(sample.repeat ?? 1) + (sample.suffix ?? ''),
    allow: sample.allow,
    deny: sample.deny,
    minLength: sample.minLength
  })
}
const double = (value) => {
  const text = String(value)
  if (!Number.isFinite(value)) throw new Error(`unexpected score ${text}`)
  if (/[.e]/.test(text)) return text.includes('.') ? text : text.replace('e', '.0e')
  return text + '.0'
}
const list = (codes) => `[${(codes ?? []).map(string).join(', ')}]`
const golden = [
  '// Generated by tools/gen_full.mjs from franc 6.2.0. Do not edit.',
  '',
  '///|',
  '/// (name, text, allow, deny, min_length, the ten best entries of',
  '/// francAll, its number of entries)',
  'let golden_cases : Array[',
  '  (',
  '    String,',
  '    String,',
  '    Array[String],',
  '    Array[String],',
  '    Int32,',
  '    Array[(String, Double)],',
  '    Int32,',
  '  ),',
  '] = ['
]
for (const c of cases) {
  const minLength = c.minLength ?? 10
  const result = francAll(c.text, {
    only: c.allow ?? [],
    ignore: c.deny ?? [],
    minLength
  })
  const best = result
    .slice(0, 10)
    .map(([code, score]) => `(${string(code)}, ${double(score)})`)
    .join(', ')
  golden.push(
    `  (${string(c.name)}, ${string(c.text)}, ${list(c.allow)}, ${list(c.deny)}, ${minLength}, [${best}], ${result.length}),`
  )
}
golden.push(
  ']',
  '',
  '///|',
  'test "francAll results match franc 6.2.0" {',
  '  let failures = []',
  '  for case in golden_cases {',
  '    let (name, text, allow, deny, min_length, best, count) = case',
  '    let actual = @full.franc_all(text, allow~, deny~, min_length~)',
  '    let top = if actual.length() > 10 { actual[:10].to_owned() } else { actual }',
  '    if top != best || actual.length() != count {',
  '      failures.push(name)',
  '    }',
  '  }',
  '  assert_eq(failures, [])',
  '  assert_true(golden_cases.length() > 150)',
  '}'
)
writeFileSync(path.join(output, 'golden_test.mbt'), golden.join('\n') + '\n')
