"""Generate unicode_case.mbt from the Unicode Character Database.

Usage: python tools/unicode_case.py [output]   (default: unicode_case.mbt)

Downloads UnicodeData.txt, SpecialCasing.txt and DerivedCoreProperties.txt
for UNICODE_VERSION and writes the tables `lowercase` in trigram.mbt needs
to reproduce JavaScript's String.prototype.toLowerCase.
"""

import sys
import urllib.request

UNICODE_VERSION = "17.0.0"
BASE = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/"


def fetch(name):
    with urllib.request.urlopen(BASE + name) as r:
        return r.read().decode("utf-8")


def data_lines(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [f.strip() for f in line.split(";")]


def parse_range(field):
    if ".." in field:
        lo, hi = field.split("..")
        return int(lo, 16), int(hi, 16)
    return int(field, 16), int(field, 16)


def merge(ranges):
    out = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(hi, out[-1][1]))
        else:
            out.append((lo, hi))
    return out


def main():
    output = sys.argv[1] if len(sys.argv) > 1 else "unicode_case.mbt"

    simple = {}
    for f in data_lines(fetch("UnicodeData.txt")):
        if f[13]:
            simple[int(f[0], 16)] = int(f[13], 16)

    # Unconditional full lowercase mappings that differ from the simple ones.
    special = {}
    for f in data_lines(fetch("SpecialCasing.txt")):
        code, lower, condition = int(f[0], 16), f[1], f[4] if len(f) > 4 else ""
        if condition:
            continue
        lower = [int(x, 16) for x in lower.split()]
        if lower != [simple.get(code, code)]:
            special[code] = lower
    # trigram.mbt handles these by hand; stop if a new Unicode version adds any.
    assert special == {0x130: [0x69, 0x307]}, special

    props = {"Cased": [], "Case_Ignorable": []}
    for f in data_lines(fetch("DerivedCoreProperties.txt")):
        if len(f) >= 2 and f[1] in props:
            props[f[1]].append(parse_range(f[0]))

    o = [
        f"// Generated by tools/unicode_case.py from Unicode {UNICODE_VERSION}. Do not edit.",
        "",
        "///|",
        "/// Code points with a simple lowercase mapping, sorted.",
        "let lower_from : FixedArray[Int] = [",
    ]
    keys = sorted(simple)
    o += [f"  0x{k:04X}," for k in keys]
    o += ["]", "", "///|", "/// `lower_from[i]` lowercases to `lower_to[i]`.", "let lower_to : FixedArray[Int] = ["]
    o += [f"  0x{simple[k]:04X}," for k in keys]
    o += ["]"]
    for name, var in (("Cased", "cased_ranges"), ("Case_Ignorable", "case_ignorable_ranges")):
        o += ["", "///|", f"/// {name} code points as sorted inclusive [lo, hi] pairs.", f"let {var} : FixedArray[Int] = ["]
        o += [f"  0x{lo:04X}, 0x{hi:04X}," for lo, hi in merge(props[name])]
        o += ["]"]

    with open(output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
