"""Writes the FLORES-200 benchmark corpus as a MoonBit file.

    python tools/gen_flores.py FLORES_DIR eval/flores/corpus.mbt

FLORES_DIR is the flores200_dataset directory of
https://dl.fbaipublicfiles.com/nllb/flores200_dataset.tar.gz (CC BY-SA 4.0;
the archive's SHA-256 is given in tools/README.md). FLORES-200 translates
the same 1012 devtest sentences, from English Wikinews, Wikijunior and
Wikivoyage, into each language, so every language gets the same content.

For each of mbglot's languages that FLORES-200 has, the script takes the
devtest sentences at the same PER_LANG positions, chosen in the order of
SHA-256("flores:<position>"), with runs of whitespace collapsed.
Northern Pashto (pbu) and Chimborazo Highland Quichua (qug) are left out:
FLORES-200 has Southern Pashto (pbt) and Ayacucho Quechua (quy) instead.
"""

import hashlib
import os
import sys

PER_LANG = 40

# mbglot language (ISO 639-3) -> FLORES-200 file name without ".devtest".
# Malay is Standard Malay (zsm), Mandarin is Simplified Chinese.
FLORES = {
    "spa": "spa_Latn", "eng": "eng_Latn", "por": "por_Latn", "ind": "ind_Latn",
    "fra": "fra_Latn", "deu": "deu_Latn", "jav": "jav_Latn", "vie": "vie_Latn",
    "ita": "ita_Latn", "tur": "tur_Latn", "pol": "pol_Latn", "swh": "swh_Latn",
    "sun": "sun_Latn", "ron": "ron_Latn", "hau": "hau_Latn", "fuv": "fuv_Latn",
    "bos": "bos_Latn", "hrv": "hrv_Latn", "nld": "nld_Latn", "srp": "srp_Cyrl",
    "ckb": "ckb_Arab", "yor": "yor_Latn", "uzn": "uzn_Latn", "zlm": "zsm_Latn",
    "ibo": "ibo_Latn", "ceb": "ceb_Latn", "tgl": "tgl_Latn", "hun": "hun_Latn",
    "azj": "azj_Latn", "ces": "ces_Latn", "run": "run_Latn", "plt": "plt_Latn",
    "nya": "nya_Latn", "kin": "kin_Latn", "zul": "zul_Latn", "swe": "swe_Latn",
    "lin": "lin_Latn", "som": "som_Latn", "ilo": "ilo_Latn", "rus": "rus_Cyrl",
    "ukr": "ukr_Cyrl", "bel": "bel_Cyrl", "bul": "bul_Cyrl", "kaz": "kaz_Cyrl",
    "arb": "arb_Arab", "urd": "urd_Arab", "pes": "pes_Arab", "hin": "hin_Deva",
    "mar": "mar_Deva", "mai": "mai_Deva", "bho": "bho_Deva", "npi": "npi_Deva",
    "mag": "mag_Deva", "cmn": "zho_Hans", "ben": "ben_Beng", "jpn": "jpn_Jpan",
    "kor": "kor_Hang", "tel": "tel_Telu", "tam": "tam_Taml", "guj": "guj_Gujr",
    "kan": "kan_Knda", "mal": "mal_Mlym", "mya": "mya_Mymr", "pan": "pan_Guru",
    "amh": "amh_Ethi", "tha": "tha_Thai", "sin": "sin_Sinh", "ell": "ell_Grek",
}

SENTENCES = 1012


def mbt_string(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 0x20:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    root, out_path = sys.argv[1], sys.argv[2]
    positions = sorted(
        range(SENTENCES),
        key=lambda i: hashlib.sha256(f"flores:{i}".encode()).digest(),
    )[:PER_LANG]
    positions.sort()
    tables = []
    for lang, name in FLORES.items():
        path = os.path.join(root, "devtest", f"{name}.devtest")
        with open(path, encoding="utf-8") as f:
            lines = [" ".join(line.split()) for line in f.read().split("\n")]
        if lines and lines[-1] == "":
            lines.pop()
        if len(lines) != SENTENCES:
            sys.exit(f"{path}: {len(lines)} lines, expected {SENTENCES}")
        tables.append((lang, [(i, lines[i]) for i in positions]))

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_flores.py from FLORES-200. Do not edit.\n")
        f.write("// FLORES-200 devtest sentences (https://github.com/facebookresearch/flores),\n")
        f.write("// CC BY-SA 4.0; this file is licensed under CC BY-SA 4.0 too.\n\n")
        for lang, rows in tables:
            enum = lang[0].upper() + lang[1:]
            f.write("///|\n")
            f.write(f"let rows_{lang} : Array[(@mbglot.Lang, Int32, String)] = [\n")
            for i, text in rows:
                f.write(f"  ({enum}, {i}, {mbt_string(text)}),\n")
            f.write("]\n\n")
        f.write("///|\n")
        f.write("/// Every language's table, in mbglot's language order.\n")
        f.write("let tables : Array[Array[(@mbglot.Lang, Int32, String)]] = [\n")
        for lang, _ in tables:
            f.write(f"  rows_{lang},\n")
        f.write("]\n")
    print(f"{len(tables)} languages, {len(tables) * PER_LANG} samples written to {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()
